#include <stdio.h>

int main(void) {

    // 문자열 포맷팅
    // printf(), scanf() 함수에서 문자열 안에 포맷 지정자를 작성하여 변수의 값을 원하는 위치에 출력하거나 입력받는 기능
    // 여러 개의 변수와 문자열을 한 번에 출력할 때 원하는 위치에 값을 넣을 수 있으며, 출력 형식을 일정하게 유지할 수 있다.

    // 자주 사용하는 포맷 지정자
    // %d   => int(정수)
    // %u   => unsigned int(부호 없는 정수)
    // %f   => float, double(실수 출력)
    // %c   => char(문자)
    // %s   => 문자열(char 배열)
    // %x   => 16진수(소문자)
    // %X   => 16진수(대문자)
    // %o   => 8진수
    // %p   => 포인터(메모리 주소)
    // %%   => % 문자 자체를 출력
    // 포맷 지정자는 출력하거나 입력하는 변수의 자료형과 반드시 일치해야 한다.
    // 자료형이 맞지 않으면 잘못된 값이 출력되거나 프로그램이 비정상적으로 동작할 수 있다.

    // 실수 출력
    // %f를 사용하면 기본적으로 소수점 이하 6자리까지 출력된다.
    // 정확히는 소수점 7번째 자리에서 반올림하여 6자리까지 표시한다.
    // %.숫자f
    // => 원하는 소수점 자리수까지 출력
    // => 지정한 자리의 다음 자리에서 반올림한 후 출력한다.

    // 출력 폭(Width) 지정
    // 포맷 지정자 앞에 숫자를 작성하면 출력할 공간의 크기를 지정할 수 있다.
    // %7d
    // => 전체 7칸을 확보한 후 오른쪽 정렬
    // %-7d
    // => 전체 7칸을 확보한 후 왼쪽 정렬
    // %07d
    // => 빈 공간을 0으로 채워 오른쪽 정렬
    // 출력할 값이 지정한 칸보다 길면 자동으로 전체 값이 그대로 출력된다.
    // 출력 폭 지정은 %d, %f, %c, %s 모두 사용할 수 있다.

    
    // 이스케이프 문자
    // 문자열 안에서 일반 문자로 표현할 수 없는 특수한 기능을 수행하는 문자
    // 모든 이스케이프 문자는 백슬래시(\)로 시작한다.
    // \n   줄바꿈(다음 줄로 이동)
    // \t   일정한 간격의 탭(Tab) 삽입
    // \\   백슬래시(\) 문자 자체를 출력
    // \"   큰따옴표(")를 문자열 안에서 출력
    // \'   작은따옴표(')를 출력
    // \r   현재 줄의 맨 앞으로 커서를 이동
    // \b   백스페이스(앞의 문자 한 글자를 지우는 효과)
    // \a   시스템 경고음(환경에 따라 동작하지 않을 수 있음)
    // \0   널 문자(Null Character), C언어 문자열의 끝을 나타내는 종료 문자

    // 문자열 종료 문자(\0)
    // => C언어의 모든 문자열은 마지막에 '\0'이 자동으로 저장된다.
    // => 문자열 관련 함수들은 '\0'을 만날 때까지 문자열을 읽는다.
    // => '\0'이 없으면 문자열의 끝을 알 수 없어 예상하지 못한 동작이 발생할 수 있다.

    int i;
    float x;
    i = 40;
    x = 839.21f;

    printf("|%d|%5d|%-5d|%5.3d|\n", i, i, i, i);
    printf("|%10.3f|%10.3e|%-10g|\n", x, x, x);

    return 0;
}